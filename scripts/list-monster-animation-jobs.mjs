import fs from 'node:fs';
import crypto from 'node:crypto';
const roots=['docs/design/characters/van-hai-monster-animation-v1','docs/design/vfx/van-hai-monster-vfx-v1'];
let jobs=roots.flatMap(root=>JSON.parse(fs.readFileSync(root+'/production-plan.json','utf8')).jobs.map(j=>({...j,root})));
const ids=process.argv.find(a=>a.startsWith('--ids='))?.slice(6).split(',');
const actor=process.argv.find(a=>a.startsWith('--actor='))?.slice(8);
const limit=Number(process.argv.find(a=>a.startsWith('--limit='))?.slice(8)??8);
if(ids)jobs=jobs.filter(j=>ids.includes(j.id));else if(actor)jobs=jobs.filter(j=>j.slug===actor);
jobs=jobs.filter(j=>!fs.existsSync(j.root+'/'+j.source)).slice(0,limit);
console.log(JSON.stringify(jobs.map(j=>({...j,promptText:fs.readFileSync(j.root+'/'+j.prompt,'utf8'),inputFiles:j.references.map(file=>({file,sha256:crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex')}))}))));
