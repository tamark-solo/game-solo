import './features/admin/admin.css';
import {GameApi} from './net/game-api';
import {createGameAdminState,GAME_ADMIN_IDS} from './core/game-admin-state';
import {AdminCoordinator} from './features/admin/coordinator';
import {attachFrameSurface} from './frame-surface';
const endpoint=import.meta.env.VITE_SERVER_URL||`${location.protocol}//${location.hostname}:2567`;
attachFrameSurface(document.querySelector<HTMLElement>('.admin-shell')!);
const state=createGameAdminState();if(new URLSearchParams(location.search).get('view')==='catalog')state.tab='catalog';
const coordinator=new AdminCoordinator(state,new GameApi(endpoint),document.getElementById(GAME_ADMIN_IDS.mount)!);
void coordinator.bootstrap();
if(import.meta.env.DEV)Object.assign(window,{__gameAdmin:()=>({authenticated:!!coordinator.state.session,role:coordinator.state.session?.account.role,busy:coordinator.state.busy,tab:coordinator.state.tab,catalogRecords:coordinator.state.catalog?.catalog?.records.length,catalogErrors:coordinator.state.catalog?.issues.filter(v=>v.severity==='error').length,accounts:coordinator.state.snapshot?.accounts.length,realms:coordinator.state.snapshot?.realms.length,message:coordinator.state.message})});
window.addEventListener('pagehide',()=>coordinator.dispose());
