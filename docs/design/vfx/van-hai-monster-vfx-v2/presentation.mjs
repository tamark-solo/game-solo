import {productionDuration,productionFrameAge,productionSample} from '../../../../client/src/core/actor-animation-production.ts';

export function profile(slug,rank){
 const radial=slug==='spirit-fungus',caster=['talisman-sprout','quiet-wisp','dark-talisman-rogue','black-silk-adept'].includes(slug),travel=caster||slug==='ink-bat';
 return {warning:radial?'radial':travel?'line':'cone',range:radial?62:travel?100:rank==='elite'?74:58,travel,hitDelay:travel?140:80,groundCharge:['jade-scute','jade-guard','cracked-puppet','spirit-fungus'].includes(slug),groundRelease:radial||slug==='jade-guard'};
}
export function presentationEnd(clip,kit,fx){
 const hitAt=productionFrameAge(clip,3)+profile(kit.id,kit.rank).hitDelay;
 return Math.max(productionDuration(clip),hitAt+productionDuration(fx.clips[kit.impact]));
}
export function reviewAge(clip,elapsed,repeat,kit,fx){
 const end=clip.action==='attack'&&kit?presentationEnd(clip,kit,fx):productionDuration(clip);
 return repeat&&!clip.loop&&!clip.holdLast?Math.max(0,elapsed)%(end+250):clip.loop?Math.max(0,elapsed)%end:Math.min(Math.max(0,elapsed),end);
}
// Facts stay external: request/contact are not generated by any frame callback.
// This page supplies a named fixture; live adapters must supply server facts.
export function fixtureFacts(clip,age,kind,p){
 const chargeAt=productionFrameAge(clip,1),releaseAt=productionFrameAge(clip,3),hitAt=releaseAt+p.hitDelay,cancelAt=releaseAt-1,cancel=kind==='cancel'&&age>=cancelAt;
 return {origin:'review-fixture',chargeAt,releaseAt,hitAt,cancelAt,cancel,warning:!cancel&&age<releaseAt,
  chargeAge:!cancel&&age>=chargeAt&&age<releaseAt?age-chargeAt:null,
  releaseAge:!cancel&&age>=releaseAt?age-releaseAt:null,
  impactAge:!cancel&&kind==='hit'&&age>=hitAt?age-hitAt:null};
}
export function effectSample(clip,age,chargeSpan){
 if(age===null||!Number.isFinite(age)||age<0)return null;
 const duration=productionDuration(clip),time=clip.phase==='charge'?age/chargeSpan*duration:age;
 if(time+1e-6>=duration)return null;
 const sample=productionSample(clip,time),progress=time/duration;
 // Dissipation uses age/opacity, never edits source pixels or restarts a timer.
 const opacity=clip.phase==='charge'?.7+.3*progress:progress<=.52?1:Math.max(0,(1-progress)/.48);
 return {...sample,opacity};
}
